import { writeFileSync } from 'node:fs'
import { browserSession } from './browser-helper.mjs'

const browser = await browserSession()
const { evaluate, until, send } = browser
try {
  await until("!!document.querySelector('.login-intro')")
  const loginScreenshot = await send('Page.captureScreenshot', { format: 'png' })
  writeFileSync(new URL('../secrets/review-login.png', import.meta.url), Buffer.from(loginScreenshot.data, 'base64'))
  await browser.login('operador')
  await until("document.querySelectorAll('.telemetria').length===3")
  if (!await evaluate("[...document.querySelectorAll('.technical-details,.simulation-controls')].every(d=>!d.open)")) throw new Error('Detalhes técnicos não iniciam recolhidos')
  const overview = await send('Page.captureScreenshot', { format: 'png', captureBeyondViewport: false })
  writeFileSync(new URL('../secrets/review-overview.png', import.meta.url), Buffer.from(overview.data, 'base64'))
  await until("document.querySelector('.card-estacao .controles button')?.textContent.includes('recarga')")
  await evaluate("document.querySelector('.technical-details').open=true;document.querySelector('.simulation-controls').open=true")
  if (!await evaluate("document.querySelector('.technical-details').textContent.includes('Temperatura') && document.querySelector('.simulation-controls').textContent.includes('Injetar falha')")) throw new Error('Controles exigidos ausentes')
  await evaluate("document.querySelector('.history-section').open=true")
  await until("document.querySelector('.sensor-history')?.textContent.includes('pontos · médias')")
  if (!await evaluate("document.querySelector('.sensor-history canvas').width>200")) throw new Error('Gráfico histórico não foi desenhado')
  const screenshot = await send('Page.captureScreenshot', { format: 'png', captureBeyondViewport: false })
  writeFileSync(new URL('../secrets/review-dashboard.png', import.meta.url), Buffer.from(screenshot.data, 'base64'))
  await browser.tab('Insights de IA')
  await until("document.querySelector('.titulo-pagina h2')?.textContent==='Manutenção preditiva'")
  await browser.tab('Laboratório e treinamento')
  await until("!!document.querySelector('.lab-advanced')")
  await evaluate("document.querySelector('.lab-advanced').open=true")
  if (!await evaluate("document.querySelectorAll('.lab-advanced input').length>=8")) throw new Error('Parâmetros avançados ausentes')
  await browser.tab('Mensageria')
  await until("document.querySelectorAll('[data-queue]').length===7")
  const busScreenshot = await send('Page.captureScreenshot', { format: 'png' })
  writeFileSync(new URL('../secrets/review-messaging.png', import.meta.url), Buffer.from(busScreenshot.data, 'base64'))
  await browser.tab('Dispositivos')
  await until("document.querySelector('.titulo-pagina h2')?.textContent==='Dispositivos'")
  await send('Emulation.setDeviceMetricsOverride', { width:390, height:844, deviceScaleFactor:1, mobile:true })
  await browser.tab('Dashboard')
  const mobileScreenshot = await send('Page.captureScreenshot', { format:'png' })
  writeFileSync(new URL('../secrets/review-mobile.png', import.meta.url), Buffer.from(mobileScreenshot.data,'base64'))
  if (!await evaluate("document.documentElement.scrollWidth<=window.innerWidth+2")) throw new Error('Dashboard ultrapassa largura móvel')
  if (browser.exceptions.length) throw new Error(browser.exceptions.join('\n'))
  console.log('PASS: interface simplificada, controles preservados, histórico Chart.js, parâmetros avançados e largura móvel')
} finally { await browser.close() }
